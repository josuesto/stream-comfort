export const messages: Record<UiLanguage, Record<MessageKey, string>> = { en, es };

export function translate(language: UiLanguage, key: MessageKey, params: MessageParams = {}): string {
  return messages[language][key].replace(/\{(\w+)\}/g, (match, name: string) => String(params[name] ?? match));
}
